import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const origin = 'https://www.avunorstudio.store';
const html = readFileSync('public/index.html', 'utf8');
assert.equal((html.match(/<h1(?:\s|>)/g) || []).length, 1);
assert.equal((html.match(/rel="canonical"/g) || []).length, 1);
assert(html.includes(`rel="canonical" href="${origin}/"`));
assert(html.includes('Website, Mobile App &amp; SaaS Development'));
assert(html.includes('Website development</h3>'));
assert(html.includes('Mobile app development</h3>'));
assert(html.includes('SaaS development</h3>'));
assert(!/<meta name="robots"[^>]*noindex/i.test(html));
const schema = JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
const organization = schema['@graph'].find(item => item['@type'] === 'Organization');
assert.equal(organization.url, origin + '/');
assert.equal(organization.email, 'avunorstudio@gmail.com');
assert.equal(organization.telephone, '+919442041516');
assert(!JSON.stringify(schema).includes('aggregateRating'));
assert(!JSON.stringify(schema).includes('reviewRating'));
const social = readFileSync('public/social-preview.png');
assert.equal(social.readUInt32BE(16), 1200);
assert.equal(social.readUInt32BE(20), 630);
const sitemap = readFileSync('public/sitemap.xml', 'utf8');
assert.equal((sitemap.match(/<loc>/g) || []).length, 4);
assert(sitemap.includes(`<loc>${origin}/</loc>`));
assert(!sitemap.includes('#'));
const robots = readFileSync('public/robots.txt', 'utf8');
assert(robots.includes(`Sitemap: ${origin}/sitemap.xml`));
assert(!/^Disallow:\s*\/\s*$/m.test(robots));
const { default: worker } = await import(pathToFileURL(process.cwd() + '/dist/server/index.js'));
const titles = new Set();
for (const file of ['website-development.html', 'mobile-app-development.html', 'saas-development.html']) {
  const page = readFileSync('public/' + file, 'utf8');
  const url = origin + '/' + file;
  assert.equal((page.match(/<h1(?:\s|>)/g) || []).length, 1);
  assert(page.includes(`rel="canonical" href="${url}"`));
  assert(page.includes(`property="og:url" content="${url}"`));
  assert(!page.includes('src="reviews.js"'));
  assert(page.includes('id="contact-launcher"'));
  assert(page.includes('id="contact-links"'));
  assert(page.includes('customers worldwide'));
  assert(html.includes(`href="${file}"`));
  assert(sitemap.includes(`<loc>${url}</loc>`));
  titles.add(page.match(/<title>(.*?)<\/title>/)[1]);
  const data = JSON.parse(page.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
  const service = data['@graph'].find(item=>item['@type']==='Service');
  const breadcrumb = data['@graph'].find(item=>item['@type']==='BreadcrumbList');
  const faq = data['@graph'].find(item=>item['@type']==='FAQPage');
  assert.equal(service.url, url);
  assert.equal(service.areaServed, 'Worldwide');
  assert.equal(service.provider['@id'], origin + '/#organization');
  assert.deepEqual(breadcrumb.itemListElement.map(item => item.item), [origin + '/', url]);
  assert.equal(faq.mainEntity.length, 4);
  assert(faq.mainEntity.every(item => item['@type'] === 'Question'));
  for (const anchor of page.matchAll(/href="(#[^"]+)"/g)) assert(page.includes(`id="${anchor[1].slice(1)}"`), file + ': ' + anchor[1]);
  const response = await worker.fetch(new Request(url), {});
  assert.equal(response.status, 200);
  assert((await response.text()).includes(`rel="canonical" href="${url}"`));
}
assert.equal(titles.size, 3);
for (const [asset, type] of [['robots.txt', 'text/plain'], ['sitemap.xml', 'application/xml'], ['social-preview.png', 'image/png'], ['avunor-symbol.png', 'image/png']]) {
  const response = await worker.fetch(new Request(origin + '/' + asset), {});
  assert.equal(response.status, 200);
  assert(response.headers.get('Content-Type').startsWith(type));
  assert.deepEqual(Buffer.from(await response.arrayBuffer()), readFileSync('public/' + asset));
}
const missing = await worker.fetch(new Request(origin + '/missing-page'), {});
assert.equal(missing.status, 404);
console.log('Passed: canonical URL, metadata, service headings, organization schema, sitemap, robots, image sizes, binary asset integrity, and 404 handling.');
